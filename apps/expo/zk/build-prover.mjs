/**
 * Builds the WebView prover: bundles prover-entry.js (snarkjs + @semaphore-protocol/proof 4.14.2)
 * for the browser and writes it into prover.html, emitted as the TypeScript module
 * prover-html.generated.ts (committed). EAS builds never run this; run it after changing the
 * entry or the Semaphore version:  node zk/build-prover.mjs   (from apps/expo)
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const out = await build({
  entryPoints: [join(dir, 'prover-entry.js')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_DEBUG': 'false', global: 'globalThis' },
  logLevel: 'warning',
});
// Never let the bundle close the inline <script> early.
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const html = readFileSync(join(dir, 'prover.html'), 'utf8').replace('/*BUNDLE*/', () => js);
writeFileSync(
  join(dir, 'prover-html.generated.ts'),
  `// GENERATED by zk/build-prover.mjs — do not edit. Semaphore 4.14.2 prover page.\n` +
    `/* eslint-disable */\nexport const PROVER_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`prover-html.generated.ts: ${(html.length / 1024).toFixed(0)} KB`);
