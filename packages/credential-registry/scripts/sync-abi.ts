/**
 * Regenerates src/abi.ts from the compiled Hardhat artifact:
 *   cd contracts/governor-contract && npx hardhat compile && cd ../../packages/credential-registry && pnpm abi
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const artifact = fileURLToPath(
  new URL(
    "../../../contracts/governor-contract/artifacts/contracts/verification-system/CredentialRegistry.sol/CredentialRegistry.json",
    import.meta.url,
  ),
);
const out = fileURLToPath(new URL("../src/abi.ts", import.meta.url));

const abi = JSON.parse(readFileSync(artifact, "utf8")).abi as Array<{ type: string; name?: string }>;

const clean = JSON.parse(
  JSON.stringify(abi, (k, v) => (k === "internalType" ? undefined : v)),
) as typeof abi;

// Every contract event a log-only indexer needs, plus the ERC-1155 mint/burn
// event. Inherited admin events (ownership, EIP-712 domain, URI, approvals,
// TransferBatch) are deliberately not part of the register.
const CONTRACT_EVENTS = [
  "TypeCreated",
  "TypeConfigured",
  "TypeRetired",
  "TypeRecognised",
  "DelegateSet",
  "OrgPrivateOnlySet",
  "BatchAdded",
  "BatchRevoked",
  "LeafRevoked",
  "Claimed",
  "SelfClaimed",
  "Renounced",
  "Pruned",
  "SourcesProposed",
  "SourcesApplied",
  "SourcesCancelled",
] as const;
const have = new Set(clean.filter((e) => e.type === "event").map((e) => e.name));
for (const e of [...CONTRACT_EVENTS, "TransferSingle"]) {
  if (!have.has(e)) throw new Error(`artifact has no event ${e}`);
}

const src = `// GENERATED by scripts/sync-abi.ts from the compiled CredentialRegistry artifact. Do not edit; run \`pnpm abi\`.
export const CREDENTIAL_REGISTRY_ABI = ${JSON.stringify(clean, null, 2)} as const;

/** The sixteen contract events plus ERC-1155 TransferSingle (mint/burn). */
export const REGISTER_EVENTS = [
${[...CONTRACT_EVENTS, "TransferSingle"].map((e) => `  "${e}",`).join("\n")}
] as const;
export type RegisterEventName = (typeof REGISTER_EVENTS)[number];
`;
writeFileSync(out, src);
console.log(`wrote ${out}`);
